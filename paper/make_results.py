# ------------------------------------------------------------------ LOO
H("Does the method label add anything? (leave-one-out)")
sys.path.insert(0, os.path.join(REPO, "01-hidden-preconditioner", "src"))
from predict_loo import best_by_cond, design            # noqa: E402
for match in ("trace", "trace_act"):
    B = best_by_cond("lit", match)
    names = [c for c in B if c in P]
    X = np.array([design(P, c) for c in names]); y = np.array([B[c] for c in names])
    errs = []
    for i in range(len(names)):
        m = np.ones(len(names), bool); m[i] = False
        coef, *_ = np.linalg.lstsq(X[m], y[m], rcond=None)
        errs.append(y[i] - float(X[i] @ coef))
    rms = float(np.sqrt(np.mean(np.square(errs))))
    print(f"- **match = {match}** ({len(names)} initializers): "
          f"`loss ≈ a + b/√r_eff^Σ + c·log tr(PΣ) + d·1[‖B₀‖>0]` predicts a "
          f"held-out method with **LOO rms {rms:.1e} nats "
          f"({rms/NULL:.1f}× the null), R² = "
          f"{1 - np.var(errs)/np.var(y):.3f}**; predicting the mean instead "
          f"gives rms {float(np.sqrt(np.mean((y-y.mean())**2))):.1e}")

