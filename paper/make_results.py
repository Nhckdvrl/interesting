def runs(d, pred=None):
    out = []
    for f in sorted(glob.glob(os.path.join(d, "*.json"))):
        try:
            r = json.load(open(f))
        except Exception:
            continue
        if "args" not in r:
            continue
        if pred is None or pred(r["args"]):
            out.append(r)
    return out


def best_curve(rs, key=lambda r: r["log"]["final_eval_loss"]):
    by = {}
    for r in rs:
        by.setdefault(r["args"]["lr"], []).append(key(r))
    m = {lr: st.mean(v) for lr, v in by.items()}
    blr = min(m, key=m.get)
    return m, blr, (blr not in (min(m), max(m)))


